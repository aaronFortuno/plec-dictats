'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const T=require('./pronunciation-table.cjs');
const {analyzeIpa}=require('./ipa-inventory.cjs');
const data=T.load(),p=data.profile,c=data.catalog;
const stats=T.summary(data.rows);
assert.equal(stats.words,c.entries.filter(e=>e.mode==='words').length);
assert.equal(stats.withIpa+stats.withoutIpa,stats.words);
const byWord=new Map(data.rows.map(row=>[row.mot,row]));
for(const [word,stress] of [['brànquia',1],['isòtop',2],['monosíl·lab',3],['pentàgon',2]])assert.equal(analyzeIpa(byWord.get(word).ipa).stressedSyllable,stress);
assert(byWord.get('brànquia').ipa.includes('ŋ'));
assert(byWord.get('isòtop').ipa.endsWith('tup'));
assert(byWord.get('monosíl·lab').ipa.includes('l.l')&&byWord.get('monosíl·lab').ipa.endsWith('p'));
T.exportData(data,true);
const tableFile=path.join(T.ROOT,p.table),original=fs.readFileSync(tableFile,'utf8');
assert.deepEqual(T.parse(T.serialize(data.rows)),data.rows);
assert.throws(()=>T.initialize(p.id));assert.equal(fs.readFileSync(tableFile,'utf8'),original);
function invalid(mutate){const rows=structuredClone(data.rows);mutate(rows);assert.throws(()=>T.validate(rows,p,c));}
invalid(rows=>rows.pop());
invalid(rows=>{rows[0]=rows[1];});
invalid(rows=>{rows[0].mot+='x';});
invalid(rows=>{rows[0].varietat='valencia';});
invalid(rows=>{rows[0].diccio='natural';});
invalid(rows=>{rows[0].ipa='wrong ipa';rows[0].estat_ipa='proposta';});
invalid(rows=>{rows.find(row=>row.ipa).estat_ipa='validada';});
invalid(rows=>{const row=rows.find(row=>row.ipa);Object.assign(row,{estat_ipa:'validada',revisor:'Prova',data_revisio:'2026-02-30'});});
const reviewed=structuredClone(data.rows),row=reviewed.find(row=>row.ipa);Object.assign(row,{estat_ipa:'validada',revisor:'Prova',data_revisio:'2026-10-24'});T.validate(reviewed,p,c);
const proposed=T.planWords(data,['brànquia','isòtop']);assert.equal(proposed.executable,false);assert.equal(proposed.entries[1].ipa,'i.ˈzɔ.tup');
assert.throws(()=>T.planWords(data,[data.rows.find(row=>!row.ipa).mot]));
const edited=structuredClone(data);edited.rows.find(row=>row.mot==='pentàgon').ipa='pən.ˈta.gun';
assert.equal(T.planWords(edited,['pentàgon']).entries[0].ipa,'pən.ˈta.gun');
assert.equal(fs.readFileSync(tableFile,'utf8'),original);
